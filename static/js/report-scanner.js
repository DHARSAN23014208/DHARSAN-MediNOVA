    function openCamera(modal, videoEl, snapBtn, retakeBtn, usePhotoBtn, snapPreviewImg, fallbackInput) {
        // Reset modal state
        if (snapPreviewImg) snapPreviewImg.style.display = 'none';
        if (videoEl) videoEl.style.display = 'block';
        if (snapBtn) snapBtn.style.display = 'inline-flex';
        if (retakeBtn) retakeBtn.style.display = 'none';
        if (usePhotoBtn) usePhotoBtn.style.display = 'none';

        if (!navigator.mediaDevices || !navigator.mediaDevices.getUserMedia) {
            handleCameraUnavailable('Camera API is not supported in this browser environment. Using direct camera file picker.', fallbackInput);
            return;
        }

        navigator.mediaDevices.getUserMedia({
            video: {
                facingMode: 'environment',
                width: { ideal: 1920 },
                height: { ideal: 1080 }
            },
            audio: false
        }).then(function (stream) {
            cameraStream = stream;
            videoEl.srcObject = stream;
            videoEl.play();
            modal.style.display = 'flex';
        }).catch(function (err) {
            console.warn('getUserMedia error:', err);
            handleCameraUnavailable('Unable to access camera (Permission denied or insecure context). Please use file capture.', fallbackInput);
        });
    }

    function handleCameraUnavailable(message, fallbackInput) {
        showScannerToast(message, 'warning');
        if (fallbackInput) {
            fallbackInput.click();
        }
    }

    function captureFrame(videoEl, canvasEl, previewImg, snapBtn, retakeBtn, usePhotoBtn) {
        if (!videoEl || !canvasEl) return;
        var width = videoEl.videoWidth || 1280;
        var height = videoEl.videoHeight || 720;

        canvasEl.width = width;
        canvasEl.height = height;
        var ctx = canvasEl.getContext('2d');
        ctx.drawImage(videoEl, 0, 0, width, height);

        var dataUrl = canvasEl.toDataURL('image/jpeg', 0.92);
        if (previewImg) {
            previewImg.src = dataUrl;
            previewImg.style.display = 'block';
        }
        videoEl.style.display = 'none';
        if (snapBtn) snapBtn.style.display = 'none';
        if (retakeBtn) retakeBtn.style.display = 'inline-flex';
        if (usePhotoBtn) usePhotoBtn.style.display = 'inline-flex';
    }

