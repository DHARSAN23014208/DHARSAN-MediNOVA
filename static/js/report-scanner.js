    /**
     * Unified Backend API Execution: POST /api/scan-report/<module_name>
     */
    function runScannerExtraction(container, mode) {
        if (!activeFile) {
            showScannerToast('Please upload or capture a lab report first.', 'warning');
            return;
        }

        var statusMessage = (mode === 'autofill')
            ? 'Extracting clinical biomarkers via AI Pipeline...'
            : 'Scanning lab report and evaluating clinical model...';

        showScannerProgress(container, statusMessage);
        disableButtons(container, true);

        var formData = new FormData();
        formData.append('report_file', activeFile);
        formData.append('mode', mode);

        fetch('/api/scan-report/' + encodeURIComponent(activeModule), {
            method: 'POST',
            body: formData
        })
            .then(function (res) {
                return res.json().then(function (data) {
                    if (!res.ok) {
                        throw new Error(data.error || 'Server returned status ' + res.status);
                    }
                    return data;
                });
            })
            .then(function (data) {
                hideScannerProgress(container);
                disableButtons(container, false);
                latestScanResult = data;

                if (mode === 'autofill') {
                    handleAutofillResponse(container, data);
                } else if (mode === 'instant_predict') {
                    handleInstantPredictResponse(container, data);
                }
            })
            .catch(function (err) {
                hideScannerProgress(container);
                disableButtons(container, false);
                console.error('Scan report error:', err);
                showScannerToast('Extraction error: ' + err.message, 'danger');
            });
    }

    /**
     * Autofill response handler: Populates matching form fields with cyan pulse
     */
    function handleAutofillResponse(container, data) {
        var values = data.values || {};
        var fieldMeta = data.field_metadata || {};
        var populatedCount = 0;

        for (var fieldName in values) {
            if (Object.prototype.hasOwnProperty.call(values, fieldName)) {
                var val = values[fieldName];
                if (val !== null && val !== undefined) {
                    var success = setFormFieldValue(fieldName, val);
                    if (success) populatedCount++;
                }
            }
        }

        renderExtractionSummary(container, data, populatedCount);
        showScannerToast('Successfully extracted ' + populatedCount + ' biomarkers from report!', 'success');

        // Smooth scroll to form fields
        var firstAutofilled = document.querySelector('.field-autofilled');
        if (firstAutofilled) {
            firstAutofilled.scrollIntoView({ behavior: 'smooth', block: 'center' });
        }
    }

    /**
     * Instant Predict response handler: Populates fields AND renders rich clinical result
     */
    function handleInstantPredictResponse(container, data) {
        // First, auto-fill extracted fields
        var values = data.values || {};
        for (var fieldName in values) {
            if (Object.prototype.hasOwnProperty.call(values, fieldName)) {
                var val = values[fieldName];
                if (val !== null && val !== undefined) {
                    setFormFieldValue(fieldName, val);
                }
            }
        }

        renderExtractionSummary(container, data, Object.keys(values).length);

        if (!data.can_predict) {
            var missing = data.missing_fields || [];
            showScannerToast('Cannot predict yet: Missing required biomarkers: ' + missing.join(', ') + '. Please review the highlighted form fields.', 'warning');
            return;
        }

        // Render Instant Prediction Result Card
        renderDynamicResultCard(data);

        // Save to Patient Health Passport (Local Encrypted/Private)
        saveToHealthPassport({
            module: activeModule,
            date: new Date().toISOString(),
            prediction: data.prediction,
            is_positive: data.is_positive,
            confidence_score: data.confidence_score,
            report_id: data.report_id,
            is_scanner: true,
            values: data.values
        });

        showScannerToast('Instant Clinical Prediction Complete!', 'success');
    }

    /**
     * Finds form element by name, id, or prefixed id and updates value.
     */
    function setFormFieldValue(fieldKey, value) {
        var lower = String(fieldKey).toLowerCase();
        var upper = String(fieldKey).toUpperCase();
        var candidates = [
            `input[name="${fieldKey}"]`,
            `input[name="${lower}"]`,
            `input[name="${upper}"]`,
            `select[name="${fieldKey}"]`,
            `select[name="${lower}"]`,
            `select[name="${upper}"]`,
            `#${fieldKey}`,
            `#${lower}`,
            `#${upper}`,
            `#k_${fieldKey}`,
            `#k_${lower}`,
            `#l_${fieldKey}`,
            `#l_${lower}`,
            `#bc_${fieldKey}`,
            `#bc_${lower}`
        ];

        var el = null;
        for (var i = 0; i < candidates.length; i++) {
            el = document.querySelector(candidates[i]);
            if (el) break;
        }

        if (!el) return false;

        // Set value based on element type
        if (el.tagName.toLowerCase() === 'select') {
            var matchFound = false;
            var strVal = String(value).toLowerCase();
            for (var j = 0; j < el.options.length; j++) {
                var optVal = el.options[j].value.toLowerCase();
                var optText = el.options[j].text.toLowerCase();
                if (optVal === strVal || optText === strVal) {
                    el.selectedIndex = j;
                    matchFound = true;
                    break;
                }
            }
            if (!matchFound) {
                el.value = value;
            }
        } else {
            el.value = value;
        }

        // Add visual pulse glow and data-source attribute
        el.classList.add('field-autofilled');
        el.setAttribute('data-extracted-source', 'scanner');

        // Dispatch events so any listening UI logic reacts
        try {
            el.dispatchEvent(new Event('input', { bubbles: true }));
            el.dispatchEvent(new Event('change', { bubbles: true }));
        } catch (e) {}

        return true;
    }

