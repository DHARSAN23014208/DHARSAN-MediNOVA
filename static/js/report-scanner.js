    function saveToHealthPassport(record) {
        try {
            var existing = [];
            var raw = localStorage.getItem('medinova_health_passport');
            if (raw) {
                existing = JSON.parse(raw);
            }
            existing.unshift(record);
            // Cap at 25 most recent screenings
            if (existing.length > 25) {
                existing = existing.slice(0, 25);
            }
            localStorage.setItem('medinova_health_passport', JSON.stringify(existing));
        } catch (e) {
            console.warn('Health passport storage failed:', e);
        }
    }

