    function setLanguage(lang) {
        currentLanguage = lang;
        if (typeof window.switchResultLanguage === 'function') {
            window.switchResultLanguage(lang);
            return;
        }

        document.querySelectorAll('.lang-btn').forEach(function (b) {
            if (b.getAttribute('data-lang') === lang) {
                b.classList.add('active');
            } else {
                b.classList.remove('active');
            }
        });

        // Translate i18n tagged elements
        document.querySelectorAll('[data-i18n]').forEach(function (el) {
            var key = el.getAttribute('data-i18n');
            var translated = getTranslation(key);
            if (translated) {
                el.textContent = translated;
            }
        });

        // Translate Result Cards (both server-rendered and dynamic scanner output)
        var resultSections = document.querySelectorAll('.result-section, .critical-alert-card, .safe-alert-card');
        resultSections.forEach(function (section) {
            var heroText = section.querySelector('.result-hero-text') || section;
            var condition = heroText.getAttribute('data-condition') || activeModule || 'heart';

            var isPositive = false;
            if (heroText.getAttribute('data-is-positive') !== null) {
                isPositive = (heroText.getAttribute('data-is-positive') === 'true');
            } else if (section.classList.contains('critical-alert-card') || section.querySelector('.critical-alert-card') || section.querySelector('.result-badge-icon.danger')) {
                isPositive = true;
            }

            var stateKey = isPositive ? 'positive' : 'negative';
            var translations = window.RESULT_TRANSLATIONS || RESULT_TRANSLATIONS;
            var conditionDict = translations[condition] || translations.heart;
            var trans = conditionDict ? conditionDict[stateKey] : null;
            if (!trans) return;

            // 1. Main Heading
            var mainHeading = section.querySelector('#resultMainHeading') || heroText.querySelector('h2');
            if (mainHeading && trans.heading && trans.heading[lang]) {
                mainHeading.textContent = trans.heading[lang];
            }

            // 2. Subheading (AI Diagnostic Assessment + Prediction)
            var subHeading = section.querySelector('#resultSubHeading') || heroText.querySelector('p:not(#resultDescription)');
            var assessmentLabel = (trans.assessment_label && trans.assessment_label[lang]) || "AI Diagnostic Assessment";
            var predictionText = (trans.prediction && trans.prediction[lang]) || (trans.prediction && trans.prediction.en) || "";
            if (subHeading) {
                subHeading.innerHTML = '<strong id="resultAssessmentLabel">' + assessmentLabel + ':</strong> <span id="resultPredictionText">' + predictionText + '</span>';
            }

            // 3. Clinical explanation paragraph
            var descriptionEl = section.querySelector('#resultDescription') || heroText.querySelectorAll('p')[1];
            if (descriptionEl && trans.description && trans.description[lang]) {
                descriptionEl.textContent = trans.description[lang];
            }

            // 4. Status badge tag
            var statusBadge = section.querySelector('#resultStatusTag') || heroText.querySelector('.result-status-tag');
            if (statusBadge && trans.badge && trans.badge[lang]) {
                statusBadge.textContent = trans.badge[lang];
            }
        });
    }

    function getTranslation(key) {
        var dict = TRANSLATIONS[currentLanguage] || TRANSLATIONS.en;
        return dict[key] || TRANSLATIONS.en[key] || '';
    }

